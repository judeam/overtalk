"""Generate the native service's typed adapter from the registered Rust commands.

This is a build-time maintenance tool, never runtime code evaluation. Rust still
checks every argument and result. Review the generated allowlist with changes.
"""
import argparse
from pathlib import Path
import re
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Reject stale adapters without modifying files")
args = parser.parse_args()

root = Path(__file__).resolve().parents[1] / "frontend/src-tauri/src"
library = (root / "lib.rs").read_text()
registered = library.split("tauri::generate_handler![", 1)[1].split("])", 1)[0]
commands = re.findall(r"^\s*([a-z_][a-z_0-9]*(?:::[a-z_][a-z_0-9]*)*)\s*,", registered, re.M)
# The native UI has no telemetry, JavaScript diagnostics, browser audio transport,
# or legacy connection/debug controls. These commands are deliberately not exposed.
excluded = {"read_audio_file", "workspace_audio_source", "workspace_release_audio", "ui_log_diagnostics"}
web_commands = commands.copy()
commands = [name for name in commands if not name.startswith(("analytics::", "console_utils::", "whisper_engine::parallel_commands::")) and name.split("::")[-1] not in excluded]


def split_parameters(text):
    text = re.sub(r"//[^\n]*", "", text)
    nesting = 0
    start = 0
    parameters = []
    for index, char in enumerate(text):
        if char in "<([": nesting += 1
        elif char in ">)]": nesting -= 1
        elif char == "," and nesting == 0:
            parameters.append(text[start:index].strip())
            start = index + 1
    if text[start:].strip(): parameters.append(text[start:].strip())
    return parameters


functions = {}
sources = sorted(root.rglob("*.rs"))
for path in sources:
    if "native_service" in path.parts or path.name.endswith(".backup"): continue
    text = path.read_text()
    for match in re.finditer(r"^(?:pub(?:\([^)]*\))?\s+)?(?P<async>async\s+)?fn\s+(?P<name>\w+)\s*(?:<[^;{]*?>)?\s*\(", text, re.M):
        start = match.end()
        nesting = 1
        end = start
        while nesting:
            char = text[end]
            nesting += (char == "(") - (char == ")")
            end += 1
        return_type = text[end:text.index("{", end)].strip()
        functions.setdefault(match["name"], []).append((path, match["async"], text[start:end - 1], return_type))

def render(selected):
    output = ["// Generated by scripts/generate-native-dispatch.py; review the allowlist.", "use super::argument;", "use serde_json::Value;", "use tauri::{AppHandle, Manager};", "", "pub(super) const COMMANDS: &[&str] = &["]
    output += [f'    "{command.split("::")[-1]}",' for command in selected]
    output += ["];", "", "pub(super) async fn dispatch(app: &AppHandle, command: &str, args: &Value) -> Result<Value, String> {", "    match command {"]
    for command in selected:
        parts = command.split("::")
        name = parts[-1]
        candidates = functions.get(name, [])
        if len(parts) == 1:
            candidates = [item for item in candidates if item[0] == root / "lib.rs"]
        else:
            prefix = {"speech": "extensions", "speakers": "extensions", "integrations": "extensions"}.get(parts[0], parts[0])
            candidates = [item for item in candidates if Path(item[0].relative_to(root).parts[0]).stem == prefix]
            if len(candidates) > 1:
                module = parts[-2]
                narrowed = [item for item in candidates if item[0].stem == module]
                if narrowed: candidates = narrowed
        if len(candidates) != 1:
            raise SystemExit(f"Ambiguous command {command}: {[str(item[0]) for item in candidates]}")
        _path, asynchronous, parameters, result_type = candidates[0]
        values = []
        for parameter in split_parameters(parameters):
            param_name, param_type = parameter.split(":", 1)
            param_name = param_name.strip().removeprefix("mut ").lstrip("_")
            if "AppHandle" in param_type:
                values.append("app.clone()")
            elif "State<" in param_type or "State <" in param_type:
                values.append("app.state()")
            else:
                camel = re.sub(r"_([a-z])", lambda m: m[1].upper(), param_name)
                values.append(f'argument(args, "{camel}")?')
        call_path = "crate::" + command
        call = f'{call_path}({", ".join(values)})' + (".await" if asynchronous else "")
        if "Result" in result_type: call += ".map_err(|error| error.to_string())?"
        if command == "utils::open_system_settings": output.append('        #[cfg(target_os = "macos")]')
        unit_result = not result_type or bool(re.match(r"->\s*(?:\(\)|Result\s*<\s*\(\)\s*[,>])", result_type))
        if unit_result:
            output.append(f'        "{name}" => {{ {call}; Ok(Value::Null) }},')
        else:
            output.append(f'        "{name}" => serde_json::to_value({call}).map_err(|error| error.to_string()),')
    output += ['        _ => Err("Unsupported native command".into()),', "    }", "}", ""]
    return output

def write_adapter(destination, lines):
    formatted = subprocess.run(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input="\n".join(lines), text=True, capture_output=True, check=True,
    ).stdout
    if args.check:
        if not destination.exists() or destination.read_text() != formatted:
            raise SystemExit(f"Stale adapter: {destination.relative_to(root)}; run scripts/generate-native-dispatch.py")
    else:
        destination.parent.mkdir(exist_ok=True)
        destination.write_text(formatted)


output = render(commands)
events = sorted(set(event for path in sources for event in re.findall(r'\.emit(?:_all)?\(\s*"([^"{}]+)"', path.read_text())))
output += ["pub(super) const EVENTS: &[&str] = &["] + [f'    "{event}",' for event in events] + ["];", ""]
destination = root / "native_service/dispatch.rs"
write_adapter(destination, output)
print(f"{'Checked' if args.check else 'Generated'} {len(commands)} typed commands and {len(events)} events")

web_output = render(web_commands)
write_adapter(root / "security/web_dispatch.rs", web_output)
print(f"{'Checked' if args.check else 'Generated'} {len(web_commands)} typed web commands")
